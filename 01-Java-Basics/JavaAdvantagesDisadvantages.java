public class JavaAdvantagesDisadvantages {

    public static void main(String[] args) {

        System.out.println("Advantages of Java:");

        System.out.println("- Platform Independent");
        System.out.println("- Object-Oriented");
        System.out.println("- Secure");
        System.out.println("- Robust");
        System.out.println("- Portable");
        System.out.println("- Multithreaded");
        System.out.println("- Automatic Memory Management");
        System.out.println("- Large Ecosystem");

        System.out.println();

        System.out.println("Disadvantages of Java:");

        System.out.println("- Higher Memory Usage");
        System.out.println("- Can be slower than lower-level languages");
        System.out.println("- Verbose Syntax");
        System.out.println("- Requires JVM");
        System.out.println("- Garbage Collection Overhead");
    }
}
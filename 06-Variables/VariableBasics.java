public class VariableBasics {

    public static void main(String[] args) {

        // Declaration
        int age;

        // Initialization
        age = 24;

        System.out.println("Age: " + age);

        // Assignment
        age = 25;

        System.out.println("Updated Age: " + age);

        String name = "Bharti";

        System.out.println("Name: " + name);
    }
}
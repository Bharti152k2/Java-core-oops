public class JavaCompilationFlow {

    public static void main(String[] args) {

        System.out.println("Java Compilation and Execution Flow");
        System.out.println();

        System.out.println("1. Write Java source code");
        System.out.println("   Example: Hello.java");

        System.out.println("2. Java compiler (javac) compiles the source code");

        System.out.println("3. Bytecode is generated");
        System.out.println("   Example: Hello.class");

        System.out.println("4. JVM loads the class");

        System.out.println("5. Bytecode is verified");

        System.out.println("6. JVM execution engine executes the bytecode");

        System.out.println("7. Program produces output");
    }
}